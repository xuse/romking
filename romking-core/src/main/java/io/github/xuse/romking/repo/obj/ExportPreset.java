package io.github.xuse.romking.repo.obj;

import java.sql.Types;
import java.time.Instant;

import com.github.xuse.querydsl.annotation.AutoGenerated;
import com.github.xuse.querydsl.annotation.GeneratedType;
import com.github.xuse.querydsl.annotation.UnsavedValue;
import com.github.xuse.querydsl.annotation.dbdef.ColumnSpec;
import com.github.xuse.querydsl.annotation.dbdef.TableSpec;

import io.github.xuse.romking.metadata.ParserType;
import lombok.Data;

/**
 * 导出预设/模板。
 * 保存常用的导出配置，方便快速复用。
 */
@Data
@TableSpec(name = "export_preset", primaryKeys = {"id"})
public class ExportPreset {

	@ColumnSpec(nullable = false, type = Types.INTEGER, unsigned = true, autoIncrement = true)
	private int id;

	/**
	 * 预设名称
	 */
	@ColumnSpec(nullable = false, size = 64, type = Types.VARCHAR)
	private String name;

	/**
	 * 源仓库标签
	 */
	@ColumnSpec(name = "source_label", nullable = false, size = 64, type = Types.VARCHAR)
	private String sourceLabel;

	/**
	 * 目标TF卡路径
	 */
	@ColumnSpec(name = "target_path", nullable = false, size = 256, type = Types.VARCHAR)
	private String targetPath;

	/**
	 * 目标仓库标签
	 */
	@ColumnSpec(name = "target_label", nullable = true, size = 64, type = Types.VARCHAR)
	private String targetLabel;

	/**
	 * 是否覆盖模式
	 */
	@ColumnSpec(name = "is_overwrite", nullable = false, type = Types.BOOLEAN, defaultValue = "false")
	private boolean overwrite;

	/**
	 * 是否快速导出
	 */
	@ColumnSpec(name = "is_quick_export", nullable = false, type = Types.BOOLEAN, defaultValue = "false")
	private boolean quickExport;

	/**
	 * 元数据格式
	 */
	@ColumnSpec(name = "metadata_format", nullable = false, size = 16, type = Types.VARCHAR, defaultValue = "'EMUELEC'")
	private ParserType metadataFormat;

	@ColumnSpec(nullable = false)
	@AutoGenerated(GeneratedType.CREATED_TIMESTAMP)
	private Instant createTime;
}
